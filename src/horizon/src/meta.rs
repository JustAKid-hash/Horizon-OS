//! Generation of the `horizon-desktop-*` meta-packages.
//!
//! The PKGBUILDs are generated from `data/desktops.toml` so there is exactly one
//! place to edit a desktop's package set. `scripts/build-repo.sh` calls this to
//! produce the packages that go into the `[horizon]` repository.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::desktops::{Catalog, Desktop};
use crate::ui;

/// The meta-package name for a desktop, e.g. `horizon-desktop-plasma`.
pub fn package_name(d: &Desktop) -> String {
    format!("horizon-desktop-{}", d.id)
}

/// Render the PKGBUILD for one desktop, including the shared package set.
pub fn render(cat: &Catalog, d: &Desktop) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# Maintainer: ZeroByte <236030943+JustAKid-hash@users.noreply.github.com>"
    );
    let _ = writeln!(
        s,
        "# Generated by `horizon desktop gen-pkgbuild {}` -- do not edit by hand.",
        d.id
    );
    let _ = writeln!(
        s,
        "# Source of truth: src/horizon/data/desktops.toml"
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "pkgname={}", package_name(d));
    let _ = writeln!(s, "pkgver=0.1.0");
    let _ = writeln!(s, "pkgrel=1");
    let _ = writeln!(s, "pkgdesc=\"Horizon OS meta-package: {}\"", d.name);
    let _ = writeln!(s, "arch=('any')");
    let _ = writeln!(
        s,
        "url=\"https://github.com/JustAKid-hash/Horizon-OS\""
    );
    let _ = writeln!(s, "license=('MIT')");
    let _ = writeln!(s, "depends=(");

    let packages = cat.full_packages(d, true);
    for p in &packages {
        let _ = writeln!(s, "  '{p}'");
    }
    let _ = writeln!(s, ")");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "# A meta-package: it ships no files, only dependencies."
    );
    let _ = writeln!(s, "package() {{");
    let _ = writeln!(s, "  :");
    let _ = writeln!(s, "}}");
    s
}

pub fn cmd_gen_pkgbuild(id: &str, out_dir: &Path) -> Result<()> {
    let cat = Catalog::load()?;
    let d = cat.find(id)?;

    fs::create_dir_all(out_dir)
        .with_context(|| format!("creating {}", out_dir.display()))?;
    let path = out_dir.join("PKGBUILD");
    fs::write(&path, render(&cat, d)).with_context(|| format!("writing {}", path.display()))?;

    println!(
        "  {} {}  {}",
        ui::green("wrote"),
        path.display(),
        ui::dim(&format!("({} dependencies)", cat.full_packages(d, true).len()))
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn package_name_format() {
        let cat = crate::desktops::Catalog::load().unwrap();
        let d = cat.find("plasma").unwrap();
        assert_eq!(package_name(d), "horizon-desktop-plasma");
    }

    #[test]
    fn render_contains_depends_and_package() {
        let cat = crate::desktops::Catalog::load().unwrap();
        let d = cat.find("xfce").unwrap();
        let s = render(&cat, d);
        assert!(s.contains("pkgname=horizon-desktop-xfce"));
        assert!(s.contains("depends=("));
        assert!(s.contains("'xfce4'"));
        assert!(s.contains("package() {"));
    }
}
